/**
 * Big display font: bold pixel caps for banners, boss names, damage numbers, combo callouts.
 * Drawn natively at 1× (no scaling of the 8 px font). Cap height 9 px, 2 px stems,
 * 2 px top/bottom strokes and 1 px middle bars (a sturdy rubber-stamp look).
 *
 * Each glyph is `height` rows of equal length: rows 0–8 are the caps, row `baseline` (9) is
 * the first row under the caps; Д, Ц, Щ, the comma, the semicolon and the parentheses hang
 * into rows 9–10.
 * Ё and Й keep their marks inside the cap height (row 0) over a 7-row body.
 * `#` = ink, `.` = empty. The renderer adds the fill colours, a 1 px outline and a shadow.
 * Advance: glyph width + `spacing`; a space advances `space` + `spacing`.
 * Caps only: upper-case the string before drawing (`'ё'.toUpperCase()` gives `Ё`).
 */
export interface BigFont {
  height: number;
  baseline: number;
  spacing: number;
  space: number;
  glyphs: Record<string, string[]>;
}

