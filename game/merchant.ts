export function merchantGreeting(seed: number, hasSales = true): string {
  const lines = [
    'Заходи, странник. Монеты в подвале не греют. А вот хорошая куртка — ещё как.',
    'Тише, не буди товар. Некоторые реликвии храпят.',
    'Слышал твои шаги ещё у лестницы. Есть чем защитить голову и чем убедить упрямую дверь.',
  ];
  return (
    lines[(seed >>> 0) % lines.length] +
    (hasSales
      ? ' На части вещей сегодня скидки — ищи красные ценники.'
      : ' Сегодня всё по обычной цене.')
  );
}
export function merchantPurchase(offer: Offer): string {
  return offer.discount
    ? `«${offer.name}» — твоя. За ${offer.cost} монет вместо ${offer.baseCost}. Сбережённое пригодится. Береги себя.`
    : `«${offer.name}» — хорошая покупка. ${offer.cost} монет, и вещь твоя. Пусть послужит дольше прежнего хозяина.`;
}
